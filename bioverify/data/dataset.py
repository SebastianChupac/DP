"""
Dataset loader for loading image pairs from CSV manifests.

Provides a convenient interface for loading pairs generated by the indexer,
with filtering and optional image loading.
"""
import os
import csv
import json
from pathlib import Path
from typing import Optional, List, Dict, Any, Callable
import numpy as np
import cv2

from .pairs import ImagePair


class PairDataset:
    """Dataset loader for image pairs from CSV manifest.
    
    Supports filtering by modality, split, dataset, and lazy image loading.
    """
    
    def __init__(
        self,
        csv_path: str,
        base_path: Optional[str] = None,
        filter_modality: Optional[str] = None,
        filter_dataset: Optional[str] = None,
        load_images: bool = False,
        transform: Optional[Callable] = None
    ):
        """Initialize pair dataset loader.
        
        Args:
            csv_path: Path to CSV manifest file
            base_path: Base path for resolving relative image paths (if None, uses CSV directory)
            filter_modality: Optional modality filter (e.g., 'iris', 'face')
            filter_dataset: Optional dataset name filter
            load_images: If True, loads images immediately; if False, only stores paths
            transform: Optional transform function to apply to loaded images
        """
        self.csv_path = csv_path
        self.base_path = base_path or os.path.dirname(csv_path)
        self.filter_modality = filter_modality
        self.filter_dataset = filter_dataset
        self.load_images = load_images
        self.transform = transform
        
        # Load and filter pairs
        self.pairs: List[ImagePair] = self._load_pairs()
        
        print(f"Loaded {len(self.pairs)} pairs from {csv_path}")
        if filter_modality:
            print(f"  Filtered by modality: {filter_modality}")
        if filter_dataset:
            print(f"  Filtered by dataset: {filter_dataset}")
    
    def _load_pairs(self) -> List[ImagePair]:
        """Load pairs from CSV file with filtering."""
        pairs = []
        
        with open(self.csv_path, 'r', encoding='utf-8') as f:
            reader = csv.DictReader(f)
            for row in reader:
                # Apply filters
                if self.filter_modality and row['modality'] != self.filter_modality:
                    continue
                if self.filter_dataset and row['dataset_name'] != self.filter_dataset:
                    continue
                
                # Parse metadata JSON
                metadata = {}
                if 'metadata' in row and row['metadata']:
                    try:
                        metadata = json.loads(row['metadata'])
                    except json.JSONDecodeError:
                        pass
                
                # Convert ground_truth string to bool
                ground_truth = row['ground_truth'].lower() in ('true', '1', 'yes')
                
                pair = ImagePair(
                    pair_id=row['pair_id'],
                    image1_path=row['image1_path'],
                    image2_path=row['image2_path'],
                    modality=row['modality'],
                    ground_truth=ground_truth,
                    identity1=row['identity1'],
                    identity2=row['identity2'],
                    dataset_name=row['dataset_name'],
                    metadata=metadata
                )
                pairs.append(pair)
        
        return pairs
    
    def __len__(self) -> int:
        """Return number of pairs in dataset."""
        return len(self.pairs)
    
    def __getitem__(self, idx: int) -> Dict[str, Any]:
        """Get a pair by index.
        
        Args:
            idx: Index of pair to retrieve
            
        Returns:
            Dictionary containing pair information and optionally loaded images
        """
        pair = self.pairs[idx]
        
        result = {
            'pair_id': pair.pair_id,
            'image1_path': self._resolve_path(pair.image1_path),
            'image2_path': self._resolve_path(pair.image2_path),
            'modality': pair.modality,
            'ground_truth': pair.ground_truth,
            'identity1': pair.identity1,
            'identity2': pair.identity2,
            'dataset_name': pair.dataset_name,
            'metadata': pair.metadata
        }
        
        # Load images if requested
        if self.load_images:
            img1 = self.load_image(result['image1_path'])
            img2 = self.load_image(result['image2_path'])
            
            if self.transform:
                img1 = self.transform(img1)
                img2 = self.transform(img2)
            
            result['image1'] = img1
            result['image2'] = img2
        
        return result
    
    def _resolve_path(self, path: str) -> str:
        """Resolve relative path to absolute path."""
        if os.path.isabs(path):
            return path
        return str(Path(self.base_path) / path)
    
    def load_image(self, path: str, as_grayscale: bool = False) -> np.ndarray:
        """Load a single image from path.
        
        Args:
            path: Path to image file
            as_grayscale: Whether to force grayscale loading
            
        Returns:
            Image as numpy array
        """
        if as_grayscale:
            img = cv2.imread(path, cv2.IMREAD_GRAYSCALE)
        else:
            img = cv2.imread(path, cv2.IMREAD_UNCHANGED)
        
        if img is None:
            raise FileNotFoundError(f"Could not load image: {path}")
        
        return img
    
    def get_statistics(self) -> Dict[str, Any]:
        """Get statistics about the loaded dataset.
        
        Returns:
            Dictionary with dataset statistics
        """
        stats = {
            'total_pairs': len(self.pairs),
            'genuine_pairs': sum(1 for p in self.pairs if p.ground_truth),
            'impostor_pairs': sum(1 for p in self.pairs if not p.ground_truth),
            'by_modality': {},
            'by_dataset': {},
            'unique_identities': len(set(
                [p.identity1 for p in self.pairs] + [p.identity2 for p in self.pairs]
            ))
        }
        
        # Count by modality and dataset
        for pair in self.pairs:
            stats['by_modality'][pair.modality] = stats['by_modality'].get(pair.modality, 0) + 1
            stats['by_dataset'][pair.dataset_name] = stats['by_dataset'].get(pair.dataset_name, 0) + 1
        
        return stats
    
    def print_statistics(self):
        """Print human-readable statistics."""
        stats = self.get_statistics()
        
        print(f"\n=== Dataset Statistics ===")
        print(f"Total pairs: {stats['total_pairs']}")
        print(f"  Genuine: {stats['genuine_pairs']} ({stats['genuine_pairs']/stats['total_pairs']*100:.1f}%)")
        print(f"  Impostor: {stats['impostor_pairs']} ({stats['impostor_pairs']/stats['total_pairs']*100:.1f}%)")
        print(f"Unique identities: {stats['unique_identities']}")
        
        print(f"\nBy modality:")
        for modality, count in stats['by_modality'].items():
            print(f"  {modality}: {count}")
        
        print(f"\nBy dataset:")
        for dataset, count in stats['by_dataset'].items():
            print(f"  {dataset}: {count}")
    
    def get_pairs_list(self) -> List[ImagePair]:
        """Get the list of ImagePair objects."""
        return self.pairs
    
    def iterate_batches(self, batch_size: int, load_images: bool = True):
        """Iterate over pairs in batches.
        
        Args:
            batch_size: Number of pairs per batch
            load_images: Whether to load images for the batch
            
        Yields:
            List of dictionaries (one per pair in batch)
        """
        for i in range(0, len(self.pairs), batch_size):
            batch = []
            for j in range(i, min(i + batch_size, len(self.pairs))):
                pair_data = self.__getitem__(j)
                if load_images and 'image1' not in pair_data:
                    # Load images if not already loaded
                    pair_data['image1'] = self.load_image(pair_data['image1_path'])
                    pair_data['image2'] = self.load_image(pair_data['image2_path'])
                batch.append(pair_data)
            yield batch
